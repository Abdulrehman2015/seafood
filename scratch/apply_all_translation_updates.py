def apply_updates(filepath, updates):
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    changed = 0
    for k, v in updates.items():
        if k in data:
            if data[k] != v:
                data[k] = v
                changed += 1
        else:
            data[k] = v
            changed += 1
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Updated {changed} keys in {filepath}")

